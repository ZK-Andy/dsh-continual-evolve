import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { openMemoryStore, type MemoryStore } from "../src/store.js";
import { SKILL_GENERATED_MARKER } from "../src/services/skill-rules.js";
import { isManagedSkillFile, reconcileSkillFiles, removeSkillFile, skillRootOf, writeSkillFile } from "../src/services/skill-files.js";
import type { SkillRecord } from "../src/store-types.js";

let roots: string[] = [];
let store: MemoryStore | undefined;
let workspace = "";

function tmpRoot(): string {
	const root = join(tmpdir(), `evolve-projection-${Math.random().toString(36).slice(2)}`);
	mkdirSync(root, { recursive: true });
	roots.push(root);
	return root;
}

function record(id: string, body = "do the thing"): SkillRecord {
	const now = new Date().toISOString();
	return {
		workspaceId: workspace,
		id,
		title: `Title ${id}`,
		description: `hook ${id}`,
		body,
		status: "active",
		sourceSession: null,
		sourceSeqs: null,
		sourceRun: null,
		createdAt: now,
		updatedAt: now,
	};
}

beforeEach(async () => {
	workspace = tmpRoot();
	store = await openMemoryStore(join(tmpRoot(), "memory.db"));
});

afterEach(() => {
	store?.close();
	store = undefined;
	for (const root of roots.splice(0)) {
		try {
			chmodSync(root, 0o700);
		} catch {
			// best effort so rm -rf below works
		}
		rmSync(root, { recursive: true, force: true });
	}
});

describe("writeSkillFile", () => {
	it("writes a managed file with the generated marker", () => {
		const root = tmpRoot();
		expect(writeSkillFile(root, record("deploy"))).toEqual([]);
		const content = readFileSync(join(root, "deploy", "SKILL.md"), "utf8");
		expect(content).toContain("generated by dsh-continual-evolve");
		expect(content).toContain("do the thing");
	});

	it("refuses ids that escape the skills root", () => {
		const root = tmpRoot();
		const warnings = writeSkillFile(root, record("../evil"));
		expect(warnings).toHaveLength(1);
		expect(warnings[0]?.warning).toContain("escapes");
		expect(existsSync(join(root, "evil"))).toBe(false);
	});
});

describe("removeSkillFile", () => {
	it("leaves missing and hand-written files alone", () => {
		const root = tmpRoot();
		expect(removeSkillFile(root, "ghost")).toEqual([]);
		mkdirSync(join(root, "hand"), { recursive: true });
		writeFileSync(join(root, "hand", "SKILL.md"), "# hand-written\n", "utf8");
		const warnings = removeSkillFile(root, "hand");
		expect(warnings).toHaveLength(1);
		expect(warnings[0]?.warning).toContain("hand-written");
		expect(existsSync(join(root, "hand", "SKILL.md"))).toBe(true);
	});

	it("removes managed files and refuses escaping ids", () => {
		const root = tmpRoot();
		writeSkillFile(root, record("deploy"));
		expect(removeSkillFile(root, "deploy")).toEqual([]);
		expect(existsSync(join(root, "deploy"))).toBe(false);
		expect(removeSkillFile(root, "../evil")[0]?.warning).toContain("escapes");
	});
});

describe("reconcileSkillFiles", () => {
	it("rewrites drifted files and removes orphan managed files", () => {
		const db = store!;
		db.applySkillProposals({ workspaceId: workspace, trigger: "explicit" }, [
			{ action: "create", id: "deploy", title: "Deploy", description: "hook", body: "steps" },
		]);
		const root = skillRootOf(workspace);
		writeFileSync(join(root, "deploy", "SKILL.md"), "# drifted\n", "utf8");
		mkdirSync(join(root, "orphan"), { recursive: true });
		writeFileSync(
			join(root, "orphan", "SKILL.md"),
			`---\nname: orphan\ndescription: gone\n---\n\n${SKILL_GENERATED_MARKER}\n\nbody\n`,
			"utf8",
		);
		const before = db.patrol();
		expect(before.skillFilesReconciled).toBeGreaterThanOrEqual(1);
		expect(before.skillOrphanFilesRemoved).toBeGreaterThanOrEqual(1);
		expect(readFileSync(join(root, "deploy", "SKILL.md"), "utf8")).toContain("steps");
		expect(existsSync(join(root, "orphan"))).toBe(false);
	});

	it("counts an orphan removal failure instead of throwing", () => {
		const db = store!;
		db.applySkillProposals({ workspaceId: workspace, trigger: "explicit" }, [
			{ action: "create", id: "deploy", title: "Deploy", description: "hook", body: "steps" },
		]);
		const root = skillRootOf(workspace);
		mkdirSync(join(root, "stuck"), { recursive: true });
		writeFileSync(
			join(root, "stuck", "SKILL.md"),
			`---\nname: stuck\ndescription: gone\n---\n\n${SKILL_GENERATED_MARKER}\n\nbody\n`,
			"utf8",
		);
		chmodSync(root, 0o555);
		try {
			const before = db.patrol();
			expect(before.skillFileErrors).toBeGreaterThanOrEqual(1);
		} finally {
			chmodSync(root, 0o700);
		}
	});

	it("rewrites a drifted file through the exported helper", () => {
		const now = new Date().toISOString();
		const row = {
			workspace_id: workspace,
			id: "deploy",
			title: "Deploy",
			description: "hook",
			body: "steps",
			status: "active",
			source_session: null,
			source_seqs: null,
			source_run: null,
			created_at: now,
			updated_at: now,
		};
		const dir = join(workspace, ".agents", "skills", "deploy");
		mkdirSync(dir, { recursive: true });
		writeFileSync(join(dir, "SKILL.md"), "# drifted\n", "utf8");
		const repos = { activeRowList: () => [row], getRow: () => row } as never;
		const result = {
			ts: now,
			orphanFtsRows: 0,
			quarantined: [],
			skillOrphanFtsRows: 0,
			skillQuarantined: [],
			skillFilesReconciled: 0,
			skillOrphanFilesRemoved: 0,
			skillFileErrors: 0,
			promptOrphanFtsRows: 0,
			promptQuarantined: [],
		};
		reconcileSkillFiles(repos, result);
		expect(result.skillFilesReconciled).toBe(1);
		expect(readFileSync(join(dir, "SKILL.md"), "utf8")).toContain("steps");
	});
});

const RETIRED_MARKER =
	"<!-- generated by dsh-continual-evolve — the central store is the source of truth; edit via skill_write, manual edits are reverted by patrol -->";

describe("isManagedSkillFile", () => {
	it("recognizes files rendered under the retired marker wording", () => {
		expect(isManagedSkillFile(RETIRED_MARKER)).toBe(true);
		expect(isManagedSkillFile(SKILL_GENERATED_MARKER)).toBe(true);
		expect(isManagedSkillFile("# hand-written\n")).toBe(false);
	});

	it("converges retired-marker files to the current render in one patrol", () => {
		const db = store!;
		db.applySkillProposals({ workspaceId: workspace, trigger: "explicit" }, [
			{ action: "create", id: "deploy", title: "Deploy", description: "hook", body: "steps" },
		]);
		const root = skillRootOf(workspace);
		writeFileSync(join(root, "deploy", "SKILL.md"), `${RETIRED_MARKER}\nbody\n`, "utf8");
		mkdirSync(join(root, "orphan"), { recursive: true });
		writeFileSync(
			join(root, "orphan", "SKILL.md"),
			`---\nname: orphan\ndescription: gone\n---\n\n${RETIRED_MARKER}\n\nbody\n`,
			"utf8",
		);
		const result = db.patrol();
		expect(result.skillFilesReconciled).toBeGreaterThanOrEqual(1);
		expect(result.skillOrphanFilesRemoved).toBeGreaterThanOrEqual(1);
		expect(readFileSync(join(root, "deploy", "SKILL.md"), "utf8")).toContain(SKILL_GENERATED_MARKER);
		expect(existsSync(join(root, "orphan"))).toBe(false);
	});
});
