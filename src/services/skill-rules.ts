/**
 * The mechanical write gates every skill passes before the store accepts it
 * — the same "模型提议，代码保证" boundary as memories, minus the
 * taxonomy: skills carry no type enum and no feedback body contract. Both
 * entry points (the explicit `evolve_write` tool and the manual move to the
 * global scope) funnel through these checks; nothing reaches the database or
 * the materialized files without them.
 *
 * File rendering follows the previously validated shape (pre-teardown
 * `skill-render.ts`, itself checked against the platform loader): YAML-ish
 * frontmatter (`name` + `description` carrying a routing hint) over the body.
 * The official skill-creator template is no longer shipped locally, so the
 * live host preset skills (same frontmatter contract) are the format anchor.
 */
import { homedir } from "node:os";
import { join, resolve, sep } from "node:path";
import {
	isValidMemoryId,
	MEMORY_BODY_LIMIT,
	MEMORY_DESCRIPTION_LIMIT,
	MEMORY_TITLE_LIMIT,
	secretLeakReason,
	slugifyId,
	textFieldGate,
} from "./memory-rules.js";

export { isValidMemoryId as isValidSkillId, slugifyId as slugifySkillId };

/** Skill scopes: project rows live in their workspace partition, global rows in `""`. */
export const SKILL_SCOPES = ["project", "global"] as const;
export type SkillScope = (typeof SKILL_SCOPES)[number];

/** The global partition id (shared with the memory store's global state rows). */
export const SKILL_GLOBAL_WORKSPACE = "";

/** Max rendered frontmatter description length (loaders truncate anyway). */
export const MAX_SKILL_DESCRIPTION_LENGTH = 240;

/**
 * Marker carried by every materialized file, right after the frontmatter.
 * Patrol only touches files carrying it — hand-written skills in the same
 * directories are never rewritten or removed.
 */
export const SKILL_GENERATED_MARKER =
	"<!-- generated by dsh-continual-evolve — the central store is the source of truth; edit via skill_write, manual edits are reverted by patrol -->";

/** One proposed skill mutation — the closed shape the write paths speak. */
export interface SkillProposal {
	action: "create" | "update" | "delete" | "move-to-global";
	/** Required for update/delete/move-to-global; optional for create (derived from title). */
	id?: string | undefined;
	/** Which partition update/delete targets. Create always lands in the project. */
	scope?: string | undefined;
	title?: string | undefined;
	description?: string | undefined;
	body?: string | undefined;
	/** Trajectory provenance ("820-831"), kept for parity with memory proposals. */
	sourceSeqs?: string | undefined;
}

/** The merged field values a create/update would write (delete checks none). */
export interface SkillFields {
	title: string;
	description: string;
	body: string;
}

/**
 * Gates that depend only on the merged field values (not on store state).
 * Runs the secret screen over the full visible text so a secret smuggled
 * into any field blocks the write.
 */
export function skillFieldGateReasons(fields: SkillFields): string[] {
	const reasons: string[] = [];
	for (const reason of [
		textFieldGate(fields.title, "title must not be empty", MEMORY_TITLE_LIMIT, `title exceeds ${MEMORY_TITLE_LIMIT} characters`),
		textFieldGate(
			fields.description,
			"description must not be empty — it is the skill trigger",
			MEMORY_DESCRIPTION_LIMIT,
			`description exceeds ${MEMORY_DESCRIPTION_LIMIT} characters`,
		),
		textFieldGate(fields.body, "body must not be empty", MEMORY_BODY_LIMIT, `body exceeds the ${MEMORY_BODY_LIMIT}-character cap`),
	]) {
		if (reason !== undefined) {
			reasons.push(reason);
		}
	}
	const leak = secretLeakReason(`${fields.title}\n${fields.description}\n${fields.body}`);
	if (leak !== undefined) {
		reasons.push(leak);
	}
	return reasons;
}

/** Collapse prose to one line for the frontmatter description. */
function oneLine(text: string): string {
	return text.replace(/\s+/g, " ").trim();
}

/**
 * First content line usable as a routing hint: non-empty, not a Markdown
 * heading, not a list marker, not frontmatter. Undefined when the body is
 * effectively empty.
 */
function routingHint(body: string): string | undefined {
	for (const rawLine of body.split("\n")) {
		const line = rawLine.trim();
		if (line.length === 0) continue;
		if (line.startsWith("#") || line.startsWith("---") || line.startsWith("-") || line.startsWith("*")) continue;
		return oneLine(line);
	}
	return undefined;
}

/**
 * Render a skill as a discoverable SKILL.md document. The frontmatter
 * description carries a routing hint — title plus the first meaningful body
 * line — instead of the bare title: the skill catalog matches on
 * description, and a title-only description gives loaders nothing to route
 * on.
 */
export function renderSkillMarkdown(skill: { id: string; title: string; description: string; body: string }): string {
	const hint = routingHint(skill.body);
	const stated = oneLine(skill.description);
	const base = oneLine(skill.title);
	// Prefer the author's own description; fall back to title + hint exactly
	// like the pre-teardown renderer so re-materialized rows stay byte-stable.
	let description: string;
	if (stated.length > 0) {
		description = stated;
	} else if (base.length === 0) {
		description = (hint ?? "").slice(0, MAX_SKILL_DESCRIPTION_LENGTH);
	} else if (hint !== undefined && !base.toLowerCase().includes(hint.toLowerCase())) {
		description = `${base} — use when: ${hint}`.slice(0, MAX_SKILL_DESCRIPTION_LENGTH);
	} else {
		description = base.slice(0, MAX_SKILL_DESCRIPTION_LENGTH);
	}
	return ["---", `name: ${skill.id}`, `description: ${description}`, "---", "", SKILL_GENERATED_MARKER, "", skill.body.trim(), ""].join("\n");
}

/**
 * Mechanical problems that would make the platform's skill loader ignore the
 * rendered file. The file is still written, but the caller surfaces these:
 * a silently ignored skill is worse than a noisy one.
 */
export function validateRenderedSkill(skill: { id: string; description: string }): string[] {
	const problems: string[] = [];
	if (!isValidMemoryId(skill.id)) {
		problems.push(`name "${skill.id}" is not kebab-case — the platform ignores the file`);
	}
	const description = oneLine(skill.description);
	if (description.length === 0) {
		problems.push("empty description — the catalog has nothing to route on");
	} else if (description.length > MAX_SKILL_DESCRIPTION_LENGTH) {
		problems.push(`description exceeds ${MAX_SKILL_DESCRIPTION_LENGTH} characters — loaders truncate it`);
	}
	if (/[\r\n]/.test(skill.description)) {
		problems.push("description spans lines — frontmatter must stay one line");
	}
	return problems;
}

/** The DSH home the global skills directory lives under (same rule as the store path). */
function dshHome(): string {
	const home = process.env.DSH_HOME?.trim();
	return home !== undefined && home.length > 0 ? home : join(homedir(), ".dsh");
}

/** Where project skills materialize: the workspace's own discovered skill directory. */
export function projectSkillsDir(workspaceId: string): string {
	return join(workspaceId, ".agents", "skills");
}

/** Where global skills materialize: the host-wide discovered skill directory. */
export function globalSkillsDir(): string {
	return join(dshHome(), "skills");
}

/**
 * The store partition a skill scope reads and writes usage in: the global
 * partition for global rows, the workspace itself otherwise. One function
 * so the tool, card, and snapshot paths cannot drift apart.
 */
export function skillUsagePartition(scope: string, cwd: string): string {
	return scope === "global" ? SKILL_GLOBAL_WORKSPACE : cwd;
}

/**
 * Resolve and defend the materialized directory for a skill id. Ids are
 * kebab slugs by gate, but the containment check stays: a caller bug must
 * never turn a skill write into a write elsewhere.
 */
export function skillDir(root: string, id: string): string {
	const base = resolve(root);
	const dir = resolve(join(base, id));
	if (dir !== base && !dir.startsWith(`${base}/`) && !dir.startsWith(`${base}${sep}`)) {
		throw new Error(`skill path escapes skills root: ${dir}`);
	}
	return dir;
}
